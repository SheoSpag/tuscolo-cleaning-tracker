export function translateTaskQuestion(question: string, language: Language): string {
  if (language === "de") {
    return question;
  }

  const dictionary = replacements[language];
  return Object.entries(dictionary)
    .sort(([left], [right]) => right.length - left.length)
    .reduce((text, [source, target]) => text.split(source).join(target), question);
}

export function translateTask(task: CleaningTask, language: Language): string {
  return translateTaskQuestion(task.question, language);
}
